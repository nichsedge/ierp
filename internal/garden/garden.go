// ResolveGardenRoot determines the target Digital Garden content directory.
func ResolveGardenRoot(customPath string) string {
	if customPath != "" {
		if abs, err := filepath.Abs(customPath); err == nil {
			return abs
		}
		return customPath
	}

	if env := os.Getenv("GARDEN_CONTENT"); env != "" {
		if abs, err := filepath.Abs(env); err == nil {
			return abs
		}
		return env
	}

	home, err := os.UserHomeDir()
	if err == nil {
		candidates := []string{
			filepath.Join(home, "Projects", "digital-graveyard", "content"),
			filepath.Join(home, "Projects", "digital-garden", "content"),
		}
		for _, c := range candidates {
			if fi, err := os.Stat(c); err == nil && fi.IsDir() {
				return c
			}
		}
		return filepath.Join(home, "Projects", "digital-graveyard", "content")
	}

	return "content"
}

var nonAlphanumericSlug = regexp.MustCompile(`[^\w\s-]`)
var spacesSlug = regexp.MustCompile(`[\s_-]+`)

// Slugify generates a filesystem-safe slug.
func Slugify(text string) string {
	cleaned := strings.ToLower(strings.TrimSpace(text))
	cleaned = nonAlphanumericSlug.ReplaceAllString(cleaned, "")
	cleaned = spacesSlug.ReplaceAllString(cleaned, "-")
	cleaned = strings.Trim(cleaned, "-")
	if cleaned == "" {
		return "untitled"
	}
	return cleaned
}

// ExportSummary contains counts of exported notes.
type ExportSummary struct {
	Projects       int `json:"projects"`
	Decisions      int `json:"decisions"`
	Retrospectives int `json:"retrospectives"`
	Gadgets        int `json:"gadgets"`
	AntiVision     int `json:"antivision"`
	Career         int `json:"career"`
}

// ExportAll writes projects, decisions, reviews, and gadgets to the Digital Garden.
func ExportAll(database *sql.DB, gardenRoot string) (*ExportSummary, error) {
	root := ResolveGardenRoot(gardenRoot)
	summary := &ExportSummary{}

	// 1. Projects
	pCount, err := ExportProjects(database, root)
	if err != nil {
		return nil, fmt.Errorf("failed exporting projects: %w", err)
	}
	summary.Projects = pCount

	// 2. Decisions (PDRs)
	dCount, err := ExportDecisions(database, root)
	if err != nil {
		return nil, fmt.Errorf("failed exporting decisions: %w", err)
	}
	summary.Decisions = dCount

	// 3. Retrospectives
	rCount, err := ExportRetrospectives(database, root)
	if err != nil {
		return nil, fmt.Errorf("failed exporting retrospectives: %w", err)
	}
	summary.Retrospectives = rCount

	// 4. Gadgets
	gCount, err := ExportGadgets(database, root)
	if err != nil {
		return nil, fmt.Errorf("failed exporting gadgets: %w", err)
	}
	summary.Gadgets = gCount

	// 5. Anti-Vision (content/Personal/Anti-Vision.md)
	avCount, err := ExportAntiVision(database, root)
	if err != nil {
		return nil, fmt.Errorf("failed exporting antivision: %w", err)
	}
	summary.AntiVision = avCount

	// 6. Career Explorations (content/Personal/Role Explorations.md)
	cCount, err := ExportCareer(database, root)
	if err != nil {
		return nil, fmt.Errorf("failed exporting career explorations: %w", err)
	}
	summary.Career = cCount

	return summary, nil
}

// ExportProjects generates markdown files in content/Knowledge/Projects/
func ExportProjects(database *sql.DB, gardenRoot string) (int, error) {
	dir := filepath.Join(gardenRoot, "Knowledge", "Projects")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return 0, err
	}

	projs, err := projects.ListProjects(database, "all")
	if err != nil {
		return 0, err
	}

	for _, p := range projs {
		filename := fmt.Sprintf("%s.md", p.Slug)
		filePath := filepath.Join(dir, filename)

		content := fmt.Sprintf(`---
title: "%s"
date: %s
tags: [project]
publish_external: true
status: "%s"
priority: "%s"
target_date: "%s"
---

# %s

> Strategic initiative tracked in iERP.

**Status**: %s | **Priority**: %s  
**Timeline**: %s → %s

## Description
%s

---
*Generated by iERP Digital Garden Sync engine.*
`, p.Title, p.CreatedAt[:10], p.Status, p.Priority, p.TargetDate,
			p.Title, p.Status, p.Priority, p.StartDate, p.TargetDate, p.Description)

		if err := os.WriteFile(filePath, []byte(content), 0644); err != nil {
			return 0, err
		}
	}

	return len(projs), nil
}

