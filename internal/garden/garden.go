// ExportAntiVision writes the Anti-Vision matrix to content/Personal/Anti-Vision.md
func ExportAntiVision(database *sql.DB, gardenRoot string) (int, error) {
	dir := filepath.Join(gardenRoot, "Personal")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return 0, err
	}

	items, err := antivision.ListAntiVision(database, "", "all")
	if err != nil {
		return 0, err
	}
	if len(items) == 0 {
		return 0, nil
	}

	activeCount := 0
	for _, it := range items {
		if it.Status == "active" {
			activeCount++
		}
	}

	today := time.Now().Format("2006-01-02")
	var sb strings.Builder

	sb.WriteString("---\n")
	sb.WriteString("title: \"Anti-Vision & Inversion Guardrails\"\n")
	sb.WriteString(fmt.Sprintf("date: %s\n", today))
	sb.WriteString(fmt.Sprintf("updated: %s\n", today))
	sb.WriteString("tags:\n")
	sb.WriteString("  - manifesto\n")
	sb.WriteString("  - life-os\n")
	sb.WriteString("  - anti-vision\n")
	sb.WriteString("  - inversion\n")
	sb.WriteString("publish_external: false\n")
	sb.WriteString(fmt.Sprintf("total_guardrails: %d\n", len(items)))
	sb.WriteString(fmt.Sprintf("active_guardrails: %d\n", activeCount))
	sb.WriteString("---\n\n")

	sb.WriteString("# 🛡️ Anti-Vision & Inversion Guardrails\n\n")
	sb.WriteString("> *\"Invert, always invert: Turn a situation or problem upside down. Look at it backward. What happens if all our plans go wrong? Where don't we want to go, and how do you get there?\"* — Charlie Munger\n>\n")
	sb.WriteString("> **Single Source of Truth**: `ierp antivision`\n\n")

	sb.WriteString("## 📊 Summary Metrics\n")
	sb.WriteString(fmt.Sprintf("- **Total Guardrails**: %d\n", len(items)))
	sb.WriteString(fmt.Sprintf("- **Active Constraints**: %d\n", activeCount))
	sb.WriteString(fmt.Sprintf("- **Last Synchronized**: %s\n\n", today))
	sb.WriteString("---\n\n")

	// Domain sections
	domainDefs := []struct {
		Key   string
		Title string
	}{
		{"work/finance", "💼 Work & Finance"},
		{"behaviour", "🧠 Behaviour & Habits"},
		{"friends", "🤝 Friends & Relationships"},
		{"fitness", "🏃 Fitness & Physicality"},
		{"family", "👨‍👩‍👧 Family"},
		{"topics", "🚫 Topics to Avoid / Filter Out"},
	}

	for _, d := range domainDefs {
		var domainItems []antivision.AntiVisionItem
		for _, it := range items {
			if strings.Contains(strings.ToLower(it.Domains), d.Key) {
				domainItems = append(domainItems, it)
			}
		}

		if len(domainItems) == 0 {
			continue
		}

		sb.WriteString(fmt.Sprintf("## %s\n\n", d.Title))
		sb.WriteString("| Guardrail / Negative Constraint | Status | Severity | Date Logged | Notes |\n")
		sb.WriteString("| :--- | :---: | :---: | :---: | :--- |\n")
		for _, it := range domainItems {
			notes := it.Notes
			if notes == "" {
				notes = "-"
			}
			statusBadge := it.Status
			if it.Status == "active" {
				statusBadge = "Active"
			} else {
				statusBadge = strings.Title(it.Status)
			}
			sb.WriteString(fmt.Sprintf("| %s | %s | %d/5 | %s | %s |\n", it.Description, statusBadge, it.Severity, it.DateLogged, notes))
		}
		sb.WriteString("\n")
	}

	sb.WriteString("---\n*Generated by iERP Digital Garden Sync engine.*\n")

	targetFile := filepath.Join(dir, "Anti-Vision.md")
	if err := os.WriteFile(targetFile, []byte(sb.String()), 0644); err != nil {
		return 0, err
	}

	return len(items), nil
}

// ExportCareer writes role explorations and skills to content/Personal/Role Explorations.md
func ExportCareer(database *sql.DB, gardenRoot string) (int, error) {
	dir := filepath.Join(gardenRoot, "Personal")
	if err := os.MkdirAll(dir, 0755); err != nil {
		return 0, err
	}

	roles, err := career.ListRoles(database, "all")
	if err != nil {
		return 0, err
	}
	skills, err := career.ListSkills(database, "all")
	if err != nil {
		return 0, err
	}

	if len(roles) == 0 && len(skills) == 0 {
		return 0, nil
	}

	today := time.Now().Format("2006-01-02")
	var sb strings.Builder

	sb.WriteString("---\n")
	sb.WriteString("title: \"Role Explorations & Vocational Experiments\"\n")
	sb.WriteString(fmt.Sprintf("date: %s\n", today))
	sb.WriteString(fmt.Sprintf("updated: %s\n", today))
	sb.WriteString("tags:\n")
	sb.WriteString("  - career\n")
	sb.WriteString("  - skills\n")
	sb.WriteString("  - experiments\n")
	sb.WriteString("  - vocational\n")
	sb.WriteString("publish_external: false\n")
	sb.WriteString(fmt.Sprintf("roles_count: %d\n", len(roles)))
	sb.WriteString(fmt.Sprintf("skills_count: %d\n", len(skills)))
	sb.WriteString("---\n\n")

	sb.WriteString("# 🧭 Role Explorations & Vocational Experiments\n\n")
	sb.WriteString("> *An internal laboratory ledger of vocational paths explored, experiments conducted, and capability inventory.*\n>\n")
	sb.WriteString("> **Scope**: Personal vocational experimentation (distinguished from the external CV showcase in `nichsedge.github.io`).\n>\n")
	sb.WriteString("> **Single Source of Truth**: `ierp roles` & `ierp skills`\n\n")
	sb.WriteString("---\n\n")

	if len(roles) > 0 {
		sb.WriteString("## 🧪 Explored Roles & Vocational Paths\n\n")
		sb.WriteString("| Role | Category | Status | Date Logged | Notes |\n")
		sb.WriteString("| :--- | :--- | :---: | :---: | :--- |\n")
		for _, r := range roles {
			notes := r.Notes
			if notes == "" {
				notes = "-"
			}
			cat := r.Category
			if cat == "" {
				cat = "-"
			}
			sb.WriteString(fmt.Sprintf("| %s | %s | %s | %s | %s |\n", r.Role, cat, strings.Title(r.Status), r.DateLogged, notes))
		}
		sb.WriteString("\n")
	}

	if len(skills) > 0 {
		sb.WriteString("## 🛠️ Capability & Skills Inventory\n\n")

		// Soft skills
		var softSkills, hardSkills []career.SkillInventory
		for _, s := range skills {
			if strings.ToLower(s.SkillType) == "soft" {
				softSkills = append(softSkills, s)
			} else {
				hardSkills = append(hardSkills, s)
			}
		}

		if len(hardSkills) > 0 {
			sb.WriteString("### Hard Skills (Technical & Quantitative)\n\n")
			sb.WriteString("| Skill | Status | Date Logged | Notes |\n")
			sb.WriteString("| :--- | :---: | :---: | :--- |\n")
			for _, s := range hardSkills {
				notes := s.Notes
				if notes == "" {
					notes = "-"
				}
				sb.WriteString(fmt.Sprintf("| %s | %s | %s | %s |\n", strings.Title(s.Skill), strings.Title(s.Status), s.DateLogged, notes))
			}
			sb.WriteString("\n")
		}

		if len(softSkills) > 0 {
			sb.WriteString("### Soft Skills (Meta & Cognitive)\n\n")
			sb.WriteString("| Skill | Status | Date Logged | Notes |\n")
			sb.WriteString("| :--- | :---: | :---: | :--- |\n")
			for _, s := range softSkills {
				notes := s.Notes
				if notes == "" {
					notes = "-"
				}
				sb.WriteString(fmt.Sprintf("| %s | %s | %s | %s |\n", strings.Title(s.Skill), strings.Title(s.Status), s.DateLogged, notes))
			}
			sb.WriteString("\n")
		}
	}

	sb.WriteString("---\n*Generated by iERP Digital Garden Sync engine.*\n")

	targetFile := filepath.Join(dir, "Role Explorations.md")
	if err := os.WriteFile(targetFile, []byte(sb.String()), 0644); err != nil {
		return 0, err
	}

	return len(roles) + len(skills), nil
}
